import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createApp } from '../server/app.mjs';
import { openStore } from '../server/store.mjs';
import { setAdminAccount } from '../server/admin-http.mjs';
test('full application migrates admin, routes protected binary uploads and login', async t => {
 const dir = await mkdtemp(join(tmpdir(),'admin-integration-'));
 const server = createApp({dataDir:dir,env:{APP_ORIGIN:'http://localhost:5174',FILES_DIR:join(dir,'private')}});
 const store = openStore(dir);
 await setAdminAccount(store,'owner','integration fixture password'); store.close();
 await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
 t.after(async()=>{server.closeAllConnections();await new Promise(resolve=>server.close(resolve));await rm(dir,{recursive:true,force:true});});
 const base = `http://127.0.0.1:${server.address().port}`;
 assert.equal((await fetch(base+'/api/admin/products')).status,401);
 assert.equal((await fetch(base+'/api/admin/messages')).status,401);
 const contact = await fetch(base+'/api/contact',{method:'POST',headers:{Origin:'http://localhost:5174','Content-Type':'application/json'},body:JSON.stringify({name:'Test customer',email:'fixture@example.test',subject:'Question STL',message:'Is this model available in another size?',website:''})});
 assert.equal(contact.status,201);
 const {reference} = await contact.json();
 const headers = {Origin:'http://localhost:5174','Content-Type':'application/json'};
 const login = await fetch(base+'/api/admin/login',{method:'POST',headers,body:JSON.stringify({username:'owner',password:'integration fixture password'})});
 assert.equal(login.status,200);
 const {csrf} = await login.json(); const cookie = login.headers.get('set-cookie').split(';')[0];
 assert.equal((await fetch(base+'/api/admin/products',{headers:{Cookie:cookie}})).status,200);
 const messages = await fetch(base+'/api/admin/messages',{headers:{Cookie:cookie}});
 assert.equal(messages.status,200);
 const inbox = await messages.json(); assert.equal(inbox.total,1); assert.equal(inbox.messages[0].reference,reference); assert.equal(inbox.messages[0].message,undefined);
 const detail = await fetch(base+'/api/admin/messages/'+reference,{headers:{Cookie:cookie}});
 assert.equal((await detail.json()).message.message,'Is this model available in another size?');
 assert.equal((await fetch(base+'/api/admin/messages?page=-1',{headers:{Cookie:cookie}})).status,400);
 const stl='solid t\nfacet normal 0 0 1\nouter loop\nvertex 0 0 0\nvertex 1 0 0\nvertex 0 1 0\nendloop\nendfacet\nendsolid t\n';
 const upload = await fetch(base+'/api/admin/files/Model_1',{method:'POST',headers:{Origin:headers.Origin,Cookie:cookie,'Content-Type':'application/octet-stream','X-CSRF-Token':csrf},body:stl});
 assert.equal(upload.status,201);
 assert.match((await upload.json()).file,/^uploads\/.*\.stl$/);
});
